# -*- coding: utf-8 -*-
"""
glossary.py

지표/용어 설명 사전 모듈.

인사이트 코멘트에 등장하는 전문 용어를 초보자도 이해할 수 있도록
간단한 설명을 붙여주는 용도입니다. (Streamlit 화면의 "용어 설명 보기"
펼치기 영역에서 사용)

사용 예:
    from glossary import GLOSSARY, get_glossary_text

    print(get_glossary_text(["RSI", "이동평균 이격도"]))
"""

GLOSSARY = {
    "이동평균": "최근 며칠간(예: 20일)의 종가를 평균 낸 값. 가격의 큰 흐름(추세)을 부드럽게 보여줍니다.",
    "이동평균 이격도": "오늘 가격이 이동평균보다 몇 % 위/아래에 있는지 나타낸 값. "
                    "많이 벗어나 있을수록 평소 흐름과 차이가 크다는 뜻입니다.",
    "RSI": "상대강도지수. 최근 가격이 얼마나 자주·많이 올랐는지를 0~100 사이 숫자로 나타낸 지표. "
           "70 이상이면 '많이 올라서 곧 쉴 수도 있다(과매수)', 30 이하면 '많이 떨어져서 반등할 수도 있다(과매도)'로 해석합니다.",
    "과매수": "가격이 단기간에 많이 올라, 추가 상승 여력보다는 조정(하락) 가능성에 좀 더 무게가 실리는 상태.",
    "과매도": "가격이 단기간에 많이 떨어져, 추가 하락보다는 반등 가능성에 좀 더 무게가 실리는 상태.",
    "거래량 배율": "오늘 거래량이 최근 평균 거래량 대비 몇 배인지 나타낸 값. 2배 이상이면 평소보다 확실히 관심이 몰렸다는 신호입니다.",
    "순매수": "매수한 금액에서 매도한 금액을 뺀 값. 양수면 '사는 쪽이 더 많았다', 음수면 '파는 쪽이 더 많았다'는 뜻입니다.",
    "괴리율": "ETF의 시장 거래 가격과, 그 ETF가 실제로 보유한 자산의 가치(NAV, 순자산가치)의 차이를 %로 나타낸 값. "
             "괴리율이 크면 ETF가 실제 가치보다 비싸게(또는 싸게) 거래되고 있다는 뜻입니다.",
    "시장 국면": "코스피 등 전체 지수의 당일 등락 폭을 기준으로 '평상시/조정/패닉' 등으로 분류한 것. "
               "같은 지표라도 시장 국면에 따라 해석이 달라질 수 있어 함께 참고합니다.",
}


def get_glossary_text(terms: list = None) -> str:
    """
    주어진 용어 목록에 대한 설명을 하나의 텍스트로 합쳐서 반환합니다.
    terms가 None이면 전체 용어 사전을 반환합니다.

    Args:
        terms: 설명을 보고 싶은 용어 이름 리스트 (예: ["RSI", "괴리율"])

    Returns:
        str: "용어: 설명" 형태로 줄바꿈된 텍스트
    """
    if terms is None:
        terms = list(GLOSSARY.keys())

    lines = []
    for term in terms:
        if term in GLOSSARY:
            lines.append(f"**{term}**: {GLOSSARY[term]}")

    return "\n\n".join(lines)


