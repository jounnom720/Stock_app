def 가격그래프(데이터, 종목명):
    그림 = go.Figure()

    그림.add_trace(go.Scatter(
        x=데이터.index,
        y=데이터["종가"],
        mode="lines",
        name="종가",
    ))
    그림.add_trace(go.Scatter(
        x=데이터.index,
        y=데이터["20일평균"],
        mode="lines",
        name="20일 평균",
    ))
    그림.add_trace(go.Scatter(
        x=데이터.index,
        y=데이터["60일평균"],
        mode="lines",
        name="60일 평균",
    ))

    그림.update_layout(
        title=f"{종목명} 주가 추이",
        xaxis_title="날짜",
        yaxis_title="가격",
        height=500,
    )
    return 그림


